using System.Net;
using System.Text.Json;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Http;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace KanbanFlow.Tests;

public sealed class OpenApiEndpointTests
{
    [Fact]
    public async Task Document_OverRealHttp_DescribesTypedResponseAndRequiredRouteParameter()
    {
        // Exercise the same AddOpenApi/MapOpenApi integration as Program.cs. A dependency
        // update must still generate a document at runtime, including typed schemas.
        var builder = WebApplication.CreateBuilder(
            new WebApplicationOptions { EnvironmentName = "Development" });
        builder.Logging.ClearProviders();
        builder.WebHost.UseUrls("http://127.0.0.1:0");
        builder.Services.AddOpenApi();

        await using var app = builder.Build();
        app.MapGet("/api/openapi-probe/{id}", (int id) => TypedResults.Ok(new OpenApiProbe(id, "Example")));
        app.MapOpenApi();

        await app.StartAsync();
        try
        {
            using var client = new HttpClient { BaseAddress = new Uri(app.Urls.Single()) };
            using var response = await client.GetAsync("/openapi/v1.json");
            var body = await response.Content.ReadAsStringAsync();
            Assert.True(response.StatusCode == HttpStatusCode.OK,
                $"OpenAPI document returned HTTP {(int)response.StatusCode}: {body}");
            using var document = JsonDocument.Parse(body);
            var root = document.RootElement;
            Assert.StartsWith("3.", root.GetProperty("openapi").GetString());

            var operation = root.GetProperty("paths").GetProperty("/api/openapi-probe/{id}").GetProperty("get");
            var parameter = Assert.Single(operation.GetProperty("parameters").EnumerateArray());
            Assert.Equal("id", parameter.GetProperty("name").GetString());
            Assert.Equal("path", parameter.GetProperty("in").GetString());
            Assert.True(parameter.GetProperty("required").GetBoolean());
            AssertSchemaType(parameter.GetProperty("schema"), "integer");

            var responseSchema = operation.GetProperty("responses").GetProperty("200")
                .GetProperty("content").GetProperty("application/json").GetProperty("schema");
            var schemaReference = responseSchema.GetProperty("$ref").GetString();
            const string schemaPrefix = "#/components/schemas/";
            Assert.StartsWith(schemaPrefix, schemaReference);
            var properties = root.GetProperty("components").GetProperty("schemas")
                .GetProperty(schemaReference![schemaPrefix.Length..]).GetProperty("properties");
            AssertSchemaType(properties.GetProperty("id"), "integer");
            AssertSchemaType(properties.GetProperty("label"), "string");
        }
        finally
        {
            await app.StopAsync();
        }
    }

    private static void AssertSchemaType(JsonElement schema, string expectedType)
    {
        // OpenAPI 3.1 permits an array of types, including the number-handling
        // alternatives generated by System.Text.Json for integer properties.
        var type = schema.GetProperty("type");
        if (type.ValueKind == JsonValueKind.Array)
            Assert.Contains(expectedType, type.EnumerateArray().Select(value => value.GetString()));
        else
            Assert.Equal(expectedType, type.GetString());
    }

    private sealed record OpenApiProbe(int Id, string Label);
}
